#!/usr/bin/env node
// Writes docs/rules.md from the sources the models actually read, so the document cannot drift from the product.
//   node tools/rules.mjs          write the file
//   node tools/rules.mjs --check  exit 1 if the file on disk is out of date

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { CAPS } from '../core/enums.js';
import { BEAT_CHECK_SYSTEM, CONCLUSION_SYSTEM, OBSERVER_SYSTEM, PLAN_RULES, SPINE_SYSTEM, TRACK_CHECK_SYSTEM, TRACKER_SYSTEM } from '../core/prompts.js';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const read = (p) => readFileSync(join(root, p), 'utf8');
const JSON_ONLY_MARK = 'Reply with one JSON object';
const quote = (text) => text.trim().split('\n').map(l => (l ? `> ${l}` : '>')).join('\n');

export function build() {
    const card = JSON.parse(read('dist/Narrator.card.json'));
    const craft = card.data.character_book.entries.map(e => {
        const flag = e.content.match(/^\{\{if \.([\w]+)\}\}/)?.[1] ?? '';
        const text = e.content.replace(/^\{\{if [^}]+\}\}|\{\{\/if\}\}$/g, '');
        return `| ${e.name} | \`${flag}\` | ${text.replace(/\|/g, '\\|')} |`;
    });
    const observerRules = OBSERVER_SYSTEM.slice(OBSERVER_SYSTEM.indexOf('Rules:'), OBSERVER_SYSTEM.indexOf('Reply with one JSON object')).trim();
    const direction = OBSERVER_SYSTEM.slice(OBSERVER_SYSTEM.lastIndexOf('"direction" is answered')).trim();
    return `# Active rules

Generated by \`npm run docs\` from the files the models read. Do not edit by hand; edit the source named under each heading and run the command again.

There are two readers. The **narrator** (your writing model) reads sections 1 to 3. The **director's models** read sections 4 and 5. Section 6 lists limits that code enforces whatever any model says.

## 1. Narrator card

Source: \`card/src/description.md\`. Sent every turn as the card's description.

${quote(card.data.description)}

## 2. Craft entries

Source: \`card/build.mjs\`. Each entry sits in the card's lorebook and is sent only while its flag is set by the director.

| Entry | Flag | Text |
| --- | --- | --- |
${craft.join('\n')}

## 3. Companion preset

Source: \`card/src/preset.md\`. The main prompt of the companion presets, \`Narrator Companion (PG)\` and \`Narrator Companion (Mature)\`. The build resolves the preset branches into two standalone files. In the PG preset the sections after 7 move up one.

${quote(read('card/src/preset.md'))}

## 4. Observer

Source: \`core/prompts.js\`. One call after every narrator reply. It records what the reply states and flags contradictions.

${quote(observerRules)}
>
${quote(direction)}

### Spine tracker

A separate call after each reply, only once the story has a spine. It reads the same reply for the spine and nothing else; the observer above does not judge the spine.

${quote(TRACKER_SYSTEM.slice(0, TRACKER_SYSTEM.indexOf(JSON_ONLY_MARK)).trim())}

### Evidence checks

The Observer checks proposed beat progress in a second call.

${quote(BEAT_CHECK_SYSTEM.slice(0, BEAT_CHECK_SYSTEM.indexOf(JSON_ONLY_MARK)).trim())}

The tracker checks its quoted claims together. Only claims that receive a confirmation are recorded.

${quote(TRACK_CHECK_SYSTEM.slice(0, TRACK_CHECK_SYSTEM.indexOf(JSON_ONLY_MARK)).trim())}

## 5. Planner

Source: \`core/prompts.js\`. Runs when a re-plan is triggered.

${quote(PLAN_RULES.replace('Planning rules:\n', ''))}

### Spine drafter

Runs once, after the arc, to draft the story's question, endings and milestones from the setup.

${quote(SPINE_SYSTEM)}

### Milestone conclusion

Runs when a milestone's checklist is fully resolved. Its text replaces the checklist.

${quote(CONCLUSION_SYSTEM)}

## 6. Enforced in code

Source: \`core/\`. No prompt can override these.

| Rule | How it is enforced |
| --- | --- |
| No quote, no change | A proposed change whose quote is not found in the reply is rejected (\`validate.js\`, \`text.js\`) |
| Nothing counts until accepted | The latest reply is provisional. It commits when the player replies; only committed replies feed the dynamic lore (\`state.js\`, \`lore.js\`) |
| One reply cannot rewrite the world | Per reply: at most ${CAPS.facts} facts, ${CAPS.relationships} relationship changes, ${CAPS.stats} stat changes, ${CAPS.statuses} status changes, ${CAPS.lore} lore drafts; one axis moves at most ${CAPS.axisPerReply} points (\`enums.js\`) |
| Presence is additive | A character leaves the scene only by a quoted departure or death, or when the scene moves to a different place (\`state.js\`) |
| Ambiguous names are refused | A name that matches two known characters never becomes a third (\`validate.js\`) |
| Canon keeps one copy | A restated fact is not recorded twice; a hint that is later stated is promoted (\`state.js\`) |
| Retcons hold | A retconned fact cannot be recorded again (\`validate.js\`, \`state.js\`) |
| One intent, never the queue | The narrator is shown the current beat only (\`brief.js\`) |
| Intents expire | A beat offered 5 turns without landing is retired, 8 if required; three "advanced" count as delivered (\`state.js\`) |
| No numbers to the narrator | Abilities and relationships reach the narrator only as words (\`social.js\`) |
| Attempt tiers need a real contest | A contest verb or "try to", exactly one named opponent, and abilities on record for both (\`social.js\`) |
| A late director does not steer | Notes built before the newest reply was read carry no intent, clue or correction (\`brief.js\`) |
| Private state stays private | Plans, clues, beliefs and canon are never written to chat variables (\`vars.js\`) |
| Code never kills a character | A serious untreated condition worsens once, to critical; mild ones never worsen on their own (\`state.js\`) |
`;
}

// pathToFileURL, not `file://${path}`: on Windows the two spellings never match and the script did nothing.
if (import.meta.url === pathToFileURL(process.argv[1]).href) {
    const out = build();
    const path = join(root, 'docs/rules.md');
    if (process.argv.includes('--check')) {
        let current = '';
        try { current = readFileSync(path, 'utf8'); } catch { /* missing */ }
        if (current !== out) { console.error('docs/rules.md is out of date. Run: npm run docs'); process.exit(1); }
    } else {
        writeFileSync(path, out);
        console.log('Wrote docs/rules.md');
    }
}
